(() => {
  const openGuide = (event) => {
    const id = event.currentTarget.dataset.sizeGuideOpen;
    const dialog = document.getElementById(id);
    if (dialog?.showModal) dialog.showModal();
  };

  document.addEventListener('click', (event) => {
    const guideTrigger = event.target.closest('[data-size-guide-open]');
    if (guideTrigger) openGuide({ currentTarget: guideTrigger });

    const closeTrigger = event.target.closest('[data-size-guide-close]');
    if (closeTrigger) closeTrigger.closest('dialog')?.close();

    if (event.target instanceof HTMLDialogElement) event.target.close();

    const tab = event.target.closest('[data-product-tab]');
    if (!tab) return;
    const container = tab.closest('[data-product-details]');
    const panelId = tab.dataset.productTab;
    if (!container || !panelId) return;
    container.querySelectorAll('[data-product-tab]').forEach((item) => item.setAttribute('aria-selected', String(item === tab)));
    container.querySelectorAll('[data-product-panel]').forEach((panel) => { panel.hidden = panel.id !== panelId; });
  });

  const formatMoney = (cents) => {
    const currency = window.Shopify?.currency?.active || 'USD';
    return new Intl.NumberFormat(document.documentElement.lang || 'en-US', {
      style: 'currency',
      currency,
      currencyDisplay: 'code',
    }).format(cents / 100);
  };

  const placeColorwayLinks = (root = document) => {
    const previewThemeId = new URLSearchParams(window.location.search).get('preview_theme_id');
    root.querySelectorAll('[data-colorway-links]').forEach((colorwayLinks) => {
      if (previewThemeId) {
        colorwayLinks.querySelectorAll('a[href]').forEach((link) => {
          const url = new URL(link.href, window.location.origin);
          url.searchParams.set('preview_theme_id', previewThemeId);
          link.href = url.pathname + url.search;
        });
      }
      const productInfo = document.querySelector('product-info');
      const variantPicker = productInfo?.querySelector('variant-radios, variant-selects');
      if (!productInfo || !variantPicker || productInfo.contains(colorwayLinks)) return;
      variantPicker.parentNode.insertBefore(colorwayLinks, variantPicker);
    });
  };

  placeColorwayLinks();
  document.addEventListener('shopify:section:load', (event) => placeColorwayLinks(event.target));

  document.querySelectorAll('[data-sneaker-sticky-bar]').forEach((bar) => {
    // Section IDs are generated by Shopify, so a template setting cannot safely
    // hard-code the product form ID. Prefer the configured ID, then fall back to
    // the native main product form in the current product-info component.
    const form =
      document.getElementById(bar.dataset.mainForm) ||
      document.querySelector('product-info product-form form[id^="product-form-"]');
    const mainAdd = form?.querySelector('button[type="submit"]');
    const productInfo = form?.closest('product-info') || document.querySelector('product-info');
    const stickyAdd = bar.querySelector('[data-sticky-add]');
    const stickyLabel = bar.querySelector('[data-sticky-add-label]');
    const stickyPrice = bar.querySelector('[data-sticky-price]');
    let variants = [];

    try {
      variants = JSON.parse(bar.dataset.variants || '[]');
    } catch (error) {
      return;
    }

    const syncStickyBar = () => {
      const selectedOptions = Array.from(productInfo?.querySelectorAll('input[type="radio"]:checked') || []).map((input) => input.value);
      const selectedVariant = variants.find((variant) => variant.options?.every((option, index) => option === selectedOptions[index]));
      const available = Boolean(selectedVariant?.available);
      stickyAdd.disabled = !available;
      stickyLabel.textContent = selectedVariant ? (available ? 'Add to cart' : 'Sold out') : 'Select options';
      if (selectedVariant && stickyPrice) stickyPrice.textContent = formatMoney(selectedVariant.price);
    };

    document.addEventListener('change', (event) => {
      if (productInfo?.contains(event.target) && event.target.matches('input[type="radio"]')) syncStickyBar();
    });
    stickyAdd?.addEventListener('click', () => mainAdd?.click());
    syncStickyBar();

    if (mainAdd && 'IntersectionObserver' in window) {
      new IntersectionObserver(([entry]) => bar.classList.toggle('is-visible', !entry.isIntersecting), { threshold: 0.15 }).observe(mainAdd);
    }
  });

  document.querySelectorAll('[data-product-meta]').forEach((meta) => {
    const productInfo = meta.closest('product-info');
    const sku = meta.querySelector('[data-product-sku]');
    let variants = [];

    try {
      variants = JSON.parse(meta.dataset.productVariants || '[]');
    } catch (error) {
      return;
    }

    const syncProductMeta = () => {
      const selectedOptions = Array.from(productInfo?.querySelectorAll('input[type="radio"]:checked') || []).map((input) => input.value);
      const selectedVariant = variants.find((variant) => variant.options?.every((option, index) => option === selectedOptions[index]));
      if (selectedVariant?.sku && sku) sku.textContent = `SKU ${selectedVariant.sku}`;
    };

    document.addEventListener('change', (event) => {
      if (productInfo?.contains(event.target) && event.target.matches('input[type="radio"]')) syncProductMeta();
    });
    syncProductMeta();
  });
})();
